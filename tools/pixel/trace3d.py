#!/usr/bin/env python3
"""Reduce the flat-colour 3D trace renders to sprite pixels: python3 tools/pixel/trace3d.py

Input: .scratch/trace/<id>[_<pose>]_<view>.png + .json from avatar/kit/render_trace.py (512 px per 1.2 m).
Each sprite pixel is a block of the render (1/16 for a 32 px Jarling): it is filled when at least half
of the block is opaque, and takes the most common colour in the block after every sample is snapped
to the nearest colour of that character's fixed palette (a majority vote, so anti-aliased seams never
invent colours). No outline here: residents.py hand-cleans the base, then outlines it (px.outline).
Feet sit on row H-2, so with the outline the figure ends on the bottom row.

Writes tools/pixel/traced.py (plain data: palette strings, so residents.py and the game need no
Blender, no PNGs). Scale per character: SCALE below (sprite px for the idle figure, outline included).
"""
import json, os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(ROOT, ".scratch", "trace")
sys.path.insert(0, HERE)
from px import OUT, PAPER

# fixed palettes (look.md "Fixed colours"), one letter each; "." is transparent
PAL = {
    "mole": {"s": "#56607A", "b": "#8792AC", "p": "#F2A0A8", "n": "#E0607A", "w": "#B07A3C", "t": "#B8C4D0",
             "o": OUT, "W": "#FFFFFF"},
    "gnome_foreman": {"c": "#1E9AA0", "h": "#F4F1E6", "b": "#EDE6D6", "v": "#F7932F", "s": "#E8B48C",
                      "n": "#E59A86", "k": "#4A3B3B", "w": "#B07A3C", "P": PAPER, "y": "#FFD23F", "o": OUT},
    "caveman": {"h": "#7A4A2A", "s": "#D99A6C", "t": "#D9A441", "d": "#7C4E24", "i": "#BFE6F5", "c": "#F3EAD2",
                "g": "#1E9AA0", "w": "#B07A3C", "o": OUT, "W": "#FFFFFF"},
    "dragon": {"l": "#A88BE0", "S": "#8C6FC8", "c": "#FFF0C9", "p": "#FFB37A", "k": "#F7A6C0", "r": "#F0DAA6",
               "o": OUT, "W": "#FFFFFF"},
}
# idle figure height in sprite px, outline included. 32 px = 1.2 m (Jeff with his comb).
#   gnome 1.23 m and caveman 1.21 m are 32 px at true scale; the Mole (0.9 m) is drawn at true
#   scale too (24 px on the same 40 x 32 frame); the Dragon is fixed at 3.5 players (112 px).
SCALE = {"mole": "true", "gnome_foreman": 32, "caveman": 32, "dragon": 112}
CANVAS = {"mole": (40, 32), "gnome_foreman": (40, 32), "caveman": (40, 32), "dragon": (128, 112)}
JOBS = [  # (character, tag, view)
    ("mole", "", "front"), ("mole", "", "side"), ("mole", "", "back"), ("mole", "popup", "front"), ("mole", "dig", "front"),
    ("gnome_foreman", "", "front"), ("gnome_foreman", "", "side"), ("gnome_foreman", "", "back"),
    ("gnome_foreman", "whistle", "front"), ("gnome_foreman", "whistle", "side"),
    ("caveman", "", "front"), ("caveman", "", "side"), ("caveman", "", "back"),
    ("caveman", "polish", "front"), ("caveman", "wave", "front"),
    ("dragon", "", "front"), ("dragon", "", "side"), ("dragon", "", "back"), ("dragon", "yawn", "front"),
]
HEADROOM = 4
N = 6  # samples per axis per sprite pixel


def rgb(h): h = h.lstrip("#"); return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def scale_for(cid):
    """Sprite px per render px, from the idle front view's height."""
    m = json.load(open(os.path.join(SRC, f"{cid}.json")))
    v = m["views"]["front"]
    hpx = v["height_m"] * m["px_per_m"]
    tgt = SCALE[cid]
    if tgt == "true":
        tgt = round(v["height_m"] / 1.2 * 32)
    return (tgt - 2) / hpx, tgt


def reduce(cid, tag, view, s):
    name = cid + (f"_{tag}" if tag else "")
    meta = json.load(open(os.path.join(SRC, f"{name}.json")))["views"][view]
    im = Image.open(os.path.join(SRC, meta["file"])).convert("RGBA")
    src = im.load(); W, H = CANVAS[cid]
    H += HEADROOM                     # rows above the frame, so rounding never clips a hat tip (fin() checks the fit)
    pal = [(k, rgb(c)) for k, c in PAL[cid].items()]
    cache = {}

    def snap(c):
        if c not in cache:
            cache[c] = min(pal, key=lambda p: sum((a - b) ** 2 for a, b in zip(p[1], c)))[0]
        return cache[c]
    g, cx = meta["ground_row"], im.width / 2
    rows = []
    for Y in range(H):
        row = ""
        for X in range(W):
            votes, n = {}, 0
            for i in range(N):
                for k in range(N):
                    sx = cx + (X - W / 2 + (k + .5) / N) / s
                    sy = g - (H - 2 - Y - (i + .5) / N) / s
                    if 0 <= sx < im.width and 0 <= sy < im.height:
                        p = src[int(sx), int(sy)]
                        if p[3] >= 128:
                            n += 1; c = snap(p[:3]); votes[c] = votes.get(c, 0) + 1
            row += max(votes, key=votes.get) if n * 2 >= N * N else "."
        rows.append(row)
    return name + "_" + view, rows


def main():
    out = ['"""Generated by tools/pixel/trace3d.py from the 3D masters (avatar/kit/render_trace.py). Do not edit:',
           're-run tools/pixel/retrace.sh. Fill only (no outline); "." is transparent."""', "",
           "PAL = " + json.dumps(PAL, indent=1), "", "HEIGHT = " + json.dumps({}), "", "BASES = {"]
    heights = {}
    for cid in PAL:
        s, tgt = scale_for(cid); heights[cid] = tgt
        for c, tag, view in [j for j in JOBS if j[0] == cid]:
            try:
                key, rows = reduce(c, tag, view, s)
                fh = sum(1 for r in rows if set(r) != {"."})
                if fh > CANVAS[c][1] - 2:          # a pose taller than the frame (the Dragon's yawn): fit it
                    key, rows = reduce(c, tag, view, s * (CANVAS[c][1] - 2) / (fh + 0.5))
                    print("  fitted", key, f"{fh} -> {CANVAS[c][1] - 2} rows")
            except FileNotFoundError as e:
                print("skip", c, tag, view, e); continue
            out.append(f" {key!r}: [")
            out += [f"  {r!r}," for r in rows]
            out.append(" ],")
            print("traced", key, f"{len(rows[0])}x{len(rows)}")
    out.append("}")
    out[5] = "HEIGHT = " + json.dumps(heights)
    open(os.path.join(HERE, "traced.py"), "w").write("\n".join(out) + "\n")
    print("wrote tools/pixel/traced.py", heights)


if __name__ == "__main__":
    main()
